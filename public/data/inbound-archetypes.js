// Inbound contact archetypes, intro funnel and calendar norms for the founder simulator.
// Research basis: docs/research/inbound-network-calendar.md (compiled 2026-10-14).
//
// Conventions
// - baseRatePerWeek: expected messages per week for the REFERENCE founder: launched, website live,
//   ~1,000 followers/audience, B2B SMB, VC-or-indie neutral, no round announced. All base rates are
//   [design] game estimates anchored on qualitative evidence. They are not measured statistics.
// - Effective rate = baseRatePerWeek
//     * multipliers.stage[stage]
//     * multipliers.visibility ** (log10(max(audience,10)) - 3)   // audience = followers + list size
//     * multipliers.model[model] * multipliers.path[path]
//     * (active trigger ? triggerBoost (or triggerBoostByEvent[event]) decaying over triggerDecayDays : 1)
//   then sample with Poisson(rate * days/7).
// - valueOutcomes p values sum to 1 and apply only if the founder engages.
// - timeCostHours: founder time if engaged (call + prep + follow-up), excluding the ~25 min refocus
//   cost in CALENDAR_NORMS.contextSwitch.
// - sources: short keys. Full dated citations are in the research doc. "[Q]" = qualitative.

